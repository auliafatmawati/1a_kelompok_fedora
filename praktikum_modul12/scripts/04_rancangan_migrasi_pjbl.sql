-- jalankan di database sipos_db
CREATE EXTENSION IF NOT EXISTS timescaledb;

CREATE TYPE role_pengguna AS ENUM ('Ketua Posyandu','Anggota BKB','Kader','Petugas Puskesmas');
CREATE TYPE jk_enum       AS ENUM ('L','P');
CREATE TYPE ya_tidak      AS ENUM ('Ya','Tidak');
CREATE TYPE gizi_enum     AS ENUM ('Gizi Baik','Berisiko Stunting','Stunting');

CREATE TABLE posyandu (
  id_posyandu   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_posyandu VARCHAR(100) NOT NULL,
  dusun VARCHAR(50), desa VARCHAR(50), kecamatan VARCHAR(50)
);

CREATE TABLE pengguna (
  id_pengguna   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_posyandu   INT NOT NULL REFERENCES posyandu(id_posyandu) ON UPDATE CASCADE,
  nama          VARCHAR(100) NOT NULL,
  username      VARCHAR(50)  NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role          role_pengguna NOT NULL DEFAULT 'Kader',
  hak_koreksi   BOOLEAN GENERATED ALWAYS AS (role IN ('Ketua Posyandu','Anggota BKB')) STORED
);

CREATE TABLE balita (
  id_balita     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_posyandu   INT NOT NULL REFERENCES posyandu(id_posyandu) ON UPDATE CASCADE,
  id_pengguna   INT NOT NULL REFERENCES pengguna(id_pengguna) ON UPDATE CASCADE,
  nik           CHAR(16) UNIQUE,
  nama          VARCHAR(100) NOT NULL,
  tgl_lahir     DATE NOT NULL,
  jenis_kelamin jk_enum NOT NULL,
  nama_ortu     VARCHAR(100) NOT NULL,
  no_wa_ortu    VARCHAR(20)
);

CREATE TABLE jadwal_posyandu (
  id_jadwal      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_posyandu    INT NOT NULL REFERENCES posyandu(id_posyandu) ON UPDATE CASCADE,
  tanggal        DATE NOT NULL,
  jam_mulai      TIME NOT NULL,
  jenis_kegiatan VARCHAR(100) NOT NULL,
  CONSTRAINT uq_jadwal_posyandu_tanggal UNIQUE (id_posyandu, tanggal)
);

CREATE TABLE kunjungan (
  id_kunjungan   BIGINT GENERATED BY DEFAULT AS IDENTITY,
  id_balita      INT NOT NULL REFERENCES balita(id_balita) ON UPDATE CASCADE,
  id_jadwal      INT NOT NULL REFERENCES jadwal_posyandu(id_jadwal) ON UPDATE CASCADE,
  id_pengguna    INT NOT NULL REFERENCES pengguna(id_pengguna) ON UPDATE CASCADE,
  tgl_kunjungan  TIMESTAMPTZ NOT NULL,            -- KOLOM BARU (dari jadwal)
  berat_badan    NUMERIC(5,2) NOT NULL CHECK (berat_badan > 0),
  tinggi_badan   NUMERIC(5,1) NOT NULL CHECK (tinggi_badan > 0),
  lingkar_kepala NUMERIC(4,1),
  vitamin_a      ya_tidak NOT NULL DEFAULT 'Tidak',
  obat_cacing    ya_tidak NOT NULL DEFAULT 'Tidak',
  status_gizi    gizi_enum,
  PRIMARY KEY (id_kunjungan, tgl_kunjungan),
  CONSTRAINT uq_kunjungan_balita_jadwal UNIQUE (id_balita, id_jadwal, tgl_kunjungan)
);

SELECT create_hypertable('kunjungan', 'tgl_kunjungan',
       chunk_time_interval => INTERVAL '1 month');

CREATE TABLE kunjungan_stg (LIKE kunjungan INCLUDING DEFAULTS);
ALTER TABLE kunjungan_stg DROP COLUMN tgl_kunjungan;   -- belum ada di sumber
-- (muat data MySQL ke kunjungan_stg lewat Data Transfer)

INSERT INTO kunjungan (id_kunjungan, id_balita, id_jadwal, id_pengguna, tgl_kunjungan,
                       berat_badan, tinggi_badan, lingkar_kepala, vitamin_a, obat_cacing, status_gizi)
SELECT s.id_kunjungan, s.id_balita, s.id_jadwal, s.id_pengguna,
       (j.tanggal + j.jam_mulai) AT TIME ZONE 'Asia/Jakarta',
       s.berat_badan, s.tinggi_badan, s.lingkar_kepala,
       s.vitamin_a, s.obat_cacing, s.status_gizi
FROM   kunjungan_stg s
JOIN   jadwal_posyandu j ON j.id_jadwal = s.id_jadwal;

-- sinkronkan counter identity setelah memuat ID lama
SELECT setval(pg_get_serial_sequence('kunjungan','id_kunjungan'),
              (SELECT max(id_kunjungan) FROM kunjungan));
